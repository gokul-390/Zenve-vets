// Local storage keys
const CUSTOM_PROFILES_KEY = 'zenve_custom_profiles';
const FOLLOW_MAP_KEY = 'zenve_following_map';

/**
 * Retrieve user-created profiles from localStorage with guaranteed photos
 */
export function getCustomProfiles() {
  try {
    const raw = localStorage.getItem(CUSTOM_PROFILES_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed)) return [];
    return parsed.map((p) => ({
      ...p,
      img: getDoctorImage(p),
    }));
  } catch {
    return [];
  }
}

/**
 * Save newly registered doctor profile
 */
export function saveCustomProfile(profileData) {
  try {
    const current = getCustomProfiles();
    const initials = (profileData.fullName || 'Dr.')
      .replace(/^Dr\.?\s*/i, '')
      .split(' ')
      .map((w) => w[0])
      .join('')
      .substring(0, 2)
      .toUpperCase() || 'DV';

    const resolvedImg = getDoctorImage(profileData);

    const newProfile = {
      id: `doc-${Date.now()}`,
      name: profileData.fullName.startsWith('Dr.') ? profileData.fullName : `Dr. ${profileData.fullName}`,
      specialty: profileData.specialty || 'General Veterinary Medicine',
      city: (profileData.cityState || 'India').split(',')[0].trim(),
      location: profileData.cityState || 'India',
      img: resolvedImg,
      initials,
      color: '#DCE9E0',
      clinic: profileData.workingPlace || 'Independent Veterinary Practice',
      experience: profileData.experience ? `${profileData.experience} years experience` : '5+ years experience',
      casesHandled: '150+',
      followers: '100+',
      rating: '5.0 ★',
      about: profileData.aboutYou || 'Dedicated veterinary professional dedicated to high quality animal health and wellbeing.',
      focusAreas: [profileData.specialty || 'Veterinary Care', 'Clinical Practice', 'Preventive Health'],
      verified: true,
    };

    const updated = [newProfile, ...current];
    localStorage.setItem(CUSTOM_PROFILES_KEY, JSON.stringify(updated));

    // Dispatch global event for instant sync across tabs/components
    window.dispatchEvent(new CustomEvent('zenve_profiles_updated', { detail: newProfile }));
    return newProfile;
  } catch (err) {
    console.error('Error saving custom profile:', err);
    return null;
  }
}

/**
 * Get all combined profiles (user created + initial community profiles)
 * Guarantees every doctor has a valid, visible photo (him or her)
 */
export function getAllProfiles() {
  const custom = getCustomProfiles();
  const all = [...custom, ...INITIAL_COMMUNITY_PROFILES];
  return all.map((p) => ({
    ...p,
    img: getDoctorImage(p),
  }));
}

/**
 * Follow / Connect state helper
 */
export function getFollowMap() {
  try {
    const raw = localStorage.getItem(FOLLOW_MAP_KEY);
    return raw ? JSON.parse(raw) : {};
  } catch {
    return {};
  }
}

export function toggleFollow(doctorId) {
  try {
    const map = getFollowMap();
    map[doctorId] = !map[doctorId];
    localStorage.setItem(FOLLOW_MAP_KEY, JSON.stringify(map));
    window.dispatchEvent(new CustomEvent('zenve_follow_updated', { detail: { doctorId, isFollowing: map[doctorId] } }));
    return map[doctorId];
  } catch {
    return false;
  }
}
